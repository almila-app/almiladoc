import contextlib
import io
import shutil
import unittest
from pathlib import Path
from unittest.mock import patch

from test_fixtures import FixtureCase


class FixtureIntegrity(FixtureCase):
    def test_assume_unchanged_caller_edit_is_refused_before_generation(self):
        self.git("update-index", "--assume-unchanged", self.other)
        target = self.root / self.other
        target.write_bytes(b"unkept caller bytes")
        self.module.GENERATE = self.command(
            f"Path({self.other!r}).write_bytes(b'fixture'); Path('generated.marker').touch()"
        )
        code, output = self.regen()
        self.assertEqual(code, 2, output)
        self.assertEqual(target.read_bytes(), b"unkept caller bytes")
        self.assertFalse((self.root / "generated.marker").exists())

    def test_assume_unchanged_generated_edit_is_refused_and_restored(self):
        self.git("update-index", "--assume-unchanged", self.other)
        self.module.GENERATE = self.command(
            f"Path({self.other!r}).write_bytes(b'unkept generated bytes')"
        )
        code, output = self.regen()
        self.assertEqual(code, 2, output)
        self.assertIn("generator changed", output)
        self.assertEqual((self.root / self.other).read_bytes(), b"fixture")
        self.assert_original()

    def test_unreadable_proposal_cannot_prevent_restoration(self):
        pending = self.main.with_name(self.main.name + ".new")
        raw = b"---\nsource: unreadable probe\n---\nraw proposal\r\n"
        self.module.GENERATE = self.command(
            f"Path({self.fixture!r}).write_bytes(b'changed fixture'); "
            f"Path({str(self.main)!r}).write_text('changed accepted snapshot'); "
            f"p=Path({str(pending)!r}); p.write_bytes({raw!r}); p.chmod(0); raise SystemExit(3)"
        )
        code, output = self.regen()
        self.assertEqual(code, 1, output)
        self.assertEqual((self.root / self.fixture).read_bytes(), b"fixture")
        self.assert_original()
        self.assertEqual(pending.stat().st_mode & 0o777, 0)
        pending.chmod(0o600)
        self.assertEqual(pending.read_bytes(), raw)

    def test_hardlinked_accepted_snapshot_does_not_overwrite_another_file(self):
        outside = self.root / "outside-owned-sentinel"
        outside.write_bytes(b"outside must survive\n")
        self.main.unlink()
        self.main.hardlink_to(outside)
        code, output = self.regen()
        self.assertEqual(outside.read_bytes(), b"outside must survive\n")
        self.assertEqual(code, 0, output)
        self.assert_accepted()

    def test_readonly_accepted_snapshot_can_be_replaced(self):
        self.main.chmod(0o444)
        code, output = self.regen()
        self.assertEqual(code, 0, output)
        self.assertEqual(self.main.stat().st_mode & 0o777, 0o444)
        self.assert_accepted()

    def readonly_directory(self):
        directory = self.root / "tests/readonly/nested"
        directory.mkdir(parents=True)
        sentinel = directory / "keep.txt"
        sentinel.write_bytes(b"unrelated source bytes")
        for path in (directory, directory.parent):
            path.chmod(0o555)
            self.addCleanup(path.chmod, 0o755)
        return directory, sentinel

    def test_success_cleans_backup_of_readonly_directories(self):
        directory, sentinel = self.readonly_directory()
        created = []
        original = self.module.tempfile.mkdtemp

        def track_scratch(*args, **kwargs):
            result = original(*args, **kwargs)
            created.append(Path(result))
            return result

        with patch.object(self.module.tempfile, "mkdtemp", side_effect=track_scratch):
            code, output = self.regen()
        self.assertEqual(code, 0, output)
        self.assert_accepted()
        self.assertEqual(sentinel.read_bytes(), b"unrelated source bytes")
        self.assertEqual(directory.stat().st_mode & 0o777, 0o555)
        self.assertTrue(created)
        self.assertTrue(all(not path.exists() for path in created))

    def test_failed_run_restores_readonly_directory_metadata(self):
        directory, sentinel = self.readonly_directory()
        self.configure(fail_final=True)
        code, output = self.regen()
        self.assertEqual(code, 1, output)
        self.assert_original()
        self.assertEqual((self.root / self.fixture).read_bytes(), b"fixture")
        self.assertEqual(sentinel.read_bytes(), b"unrelated source bytes")
        for path in (directory, directory.parent):
            self.assertEqual(path.stat().st_mode & 0o777, 0o555)

    def test_backup_cleanup_does_not_change_symlink_targets(self):
        outside = self.root / "outside-owned-directory"
        outside.mkdir()
        nested = outside / "nested"
        nested.mkdir()
        payload = nested / "keep.txt"
        payload.write_bytes(b"outside must survive")
        payload.chmod(0o444)
        nested.chmod(0o555)
        outside.chmod(0o555)
        self.addCleanup(outside.chmod, 0o755)
        self.addCleanup(nested.chmod, 0o755)
        (self.root / "tests/outside-link").symlink_to(outside, target_is_directory=True)
        for fail_final in (False, True):
            with self.subTest(fail_final=fail_final):
                self.configure(fail_final=fail_final)
                code, output = self.regen()
                self.assertEqual(code, 1 if fail_final else 0, output)
                for path in (outside, nested):
                    self.assertEqual(path.stat().st_mode & 0o777, 0o555)
                self.assertEqual(payload.stat().st_mode & 0o777, 0o444)
                self.assertEqual(payload.read_bytes(), b"outside must survive")
                self.assertTrue((self.root / "tests/outside-link").is_symlink())

    def test_failed_restoration_keeps_the_pre_run_backup(self):
        self.configure(fail_final=True)
        output = io.StringIO()
        with (
            contextlib.redirect_stdout(output),
            patch.object(self.module, "restore_tests", side_effect=OSError("restoration probe")),
            self.assertRaisesRegex(OSError, "restoration probe"),
        ):
            self.module.regen({self.fixture})
        prefix = "fixture restoration failed; pre-run backup retained at "
        lines = [
            line.removeprefix(prefix)
            for line in output.getvalue().splitlines()
            if line.startswith(prefix)
        ]
        self.assertEqual(len(lines), 1)
        backup = Path(lines[0])
        self.addCleanup(shutil.rmtree, backup.parent)
        self.assertEqual((backup / "snapshots" / self.main.name).read_text(), "old markdown\n")
        self.assertEqual(
            (backup / "fixtures/docx" / Path(self.fixture).name).read_bytes(), b"fixture"
        )


if __name__ == "__main__":
    unittest.main()
